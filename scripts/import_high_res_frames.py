"""Import matching JPEG frames and generate responsive previews for the website.

Usage: python3 scripts/import_high_res_frames.py /path/to/high-res-imgs.zip
The supplied JPEGs are preserved byte for byte. Requires Pillow.
"""

import argparse
import hashlib
import io
import json
from pathlib import Path, PurePosixPath
from zipfile import ZipFile

from PIL import Image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    frames = root / "assets" / "frames"
    expected = {p.name for p in frames.glob("*.jpg")}
    imported = {}
    with ZipFile(args.archive) as archive:
        for entry in archive.infolist():
            if entry.is_dir():
                continue
            path = PurePosixPath(entry.filename)
            if path.is_absolute() or ".." in path.parts or path.suffix.lower() != ".jpg":
                raise ValueError(f"Unexpected archive entry: {entry.filename}")
            if path.name in imported:
                raise ValueError(f"Duplicate filename: {path.name}")
            raw = archive.read(entry)
            with Image.open(io.BytesIO(raw)) as image:
                if image.format != "JPEG":
                    raise ValueError(f"Not a JPEG: {path.name}")
                image.verify()
            imported[path.name] = raw
    if set(imported) != expected:
        raise ValueError(f"Frame mismatch: missing={sorted(expected - set(imported))}; extra={sorted(set(imported) - expected)}")

    for directory in ("small", "preview"):
        (frames / directory).mkdir(exist_ok=True)
    manifest = {}
    for name, raw in sorted(imported.items()):
        (frames / name).write_bytes(raw)
        src = f"assets/frames/{name}"
        version = hashlib.sha256(raw).hexdigest()[:12]
        with Image.open(io.BytesIO(raw)) as image:
            width, height = image.size
            candidates = []
            for directory, size, quality in (("small", 160, 82), ("preview", 640, 88)):
                target_width = min(size, width)
                preview = image.convert("RGB").resize((target_width, round(target_width * height / width)), Image.Resampling.LANCZOS)
                preview.save(frames / directory / name, "JPEG", quality=quality, optimize=True, progressive=True)
                candidates.append(f"assets/frames/{directory}/{name}?v={version} {target_width}w")
            candidates.append(f"{src}?v={version} {width}w")
            manifest[src] = {"width": width, "height": height, "srcset": ", ".join(candidates)}
    output = root / "assets" / "js" / "frames.js"
    output.write_text("// Generated by scripts/import_high_res_frames.py.\nwindow.PAGE_FRAME_IMAGES = " + json.dumps(manifest, separators=(",", ":")) + ";\n")
    print(f"Imported {len(imported)} originals with 160px and 640px previews.")


if __name__ == "__main__":
    main()
